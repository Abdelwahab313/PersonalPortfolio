/**
 * Discovers every post in src/content/blog/ and regenerates
 * src/content/blog/index.js.
 *
 * A post is one file: module.exports = {slug, title, kind, status, date, ...}
 * Drop a new file in that folder, run npm start / npm run build / npm test,
 * and it appears. Never edit index.js by hand, never edit a registry.
 *
 * Authoring contract: docs/BLOG.md
 */

const fs = require("fs");
const path = require("path");
const prettier = require("prettier");

const BLOG_DIR = path.join(__dirname, "..", "src", "content", "blog");
const OUT_FILE = path.join(BLOG_DIR, "index.js");

function readPosts() {
  return fs
    .readdirSync(BLOG_DIR)
    .filter(
      name =>
        name.endsWith(".js") &&
        name !== "index.js" &&
        !name.endsWith(".test.js")
    )
    .map(name => {
      const file = path.join(BLOG_DIR, name);
      const post = require(file);
      const expected = name.replace(/\.js$/, "");

      if (!post || typeof post !== "object") {
        throw new Error(`${name}: must module.exports an object`);
      }
      if (post.slug !== expected) {
        throw new Error(
          `${name}: slug "${post.slug}" must match the filename ("${expected}")`
        );
      }
      if (
        typeof post.date !== "string" ||
        !/^\d{4}-\d{2}-\d{2}$/.test(post.date)
      ) {
        throw new Error(`${name}: date must be an ISO date string, YYYY-MM-DD`);
      }
      return post;
    });
}

function sortPosts(posts) {
  return posts.slice().sort((a, b) => {
    if (a.date !== b.date) return a.date < b.date ? 1 : -1;
    const ao = a.order || 0;
    const bo = b.order || 0;
    if (ao !== bo) return ao - bo;
    return a.slug < b.slug ? -1 : 1;
  });
}

async function writeIndex(allPosts) {
  const posts = sortPosts(allPosts);
  const bySlug = [...posts].sort((a, b) => (a.slug < b.slug ? -1 : 1));
  const imports = bySlug
    .map(p => `import ${p.slug} from "./${p.slug}";`)
    .join("\n");
  const ordered = posts.map(p => p.slug).join(", ");

  const raw = `/* GENERATED by scripts/gen-blog-index.js. Do not edit by hand. */

${imports}

export const posts = [${ordered}];
`;

  const config = await prettier.resolveConfig(OUT_FILE);
  const formatted = await prettier.format(raw, {
    ...config,
    filepath: OUT_FILE
  });
  fs.writeFileSync(OUT_FILE, formatted);
  return posts;
}

async function main() {
  const posts = await writeIndex(readPosts());
  console.log(
    `gen-blog-index: ${posts.length} post(s) -> src/content/blog/index.js`
  );
}

module.exports = {readPosts, sortPosts, writeIndex, BLOG_DIR, OUT_FILE};

if (require.main === module) {
  main().catch(err => {
    console.error(err.message || err);
    process.exit(1);
  });
}
